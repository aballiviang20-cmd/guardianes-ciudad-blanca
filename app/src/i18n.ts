export type Dict = (typeof dict)["es"];

export function useT() {
  const lang = useStore((s) => s.lang);
  return { t: dict[lang] as Dict, lang };
}

export function pick<T extends object>(obj: T, field: string, lang: Lang): string {
  const rec = obj as Record<string, unknown>;
  return (rec[`${field}_${lang}`] as string) || (rec[`${field}_es`] as string) || "";
}

export function pickList<T extends object>(obj: T, field: string, lang: Lang): string[] {
  const rec = obj as Record<string, unknown>;
  const v = rec[`${field}_${lang}`] as string[] | undefined;
  return v && v.length ? v : ((rec[`${field}_es`] as string[]) ?? []);
}
